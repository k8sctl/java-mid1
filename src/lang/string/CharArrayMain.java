package lang.string;

public class CharArrayMain {

    public static void main(String[] args) {
        char c = '가';
        System.out.println("c = " + c);

        char[] charArr = new char[]{'h', 'e', 'l', 'l', 'o'};
        System.out.println("charArr = " + charArr);

        String str = "hello";
        System.out.println("str = " + str);
    }
}
